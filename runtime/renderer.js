function translateString(value, allowSettingsFragments = false) {
    const trimmed = value.trim();
    if (!trimmed) {
        return value;
    }
    let translated = Object.hasOwn(zhCnText, trimmed) ? zhCnText[trimmed] : undefined;
    if (!translated && allowSettingsFragments) {
        translated = Object.hasOwn(zhCnSettingsFragments, trimmed) ? zhCnSettingsFragments[trimmed] : undefined;
        if (!translated && /^\d+ projects?$/.test(trimmed)) {
            translated = trimmed.replace(/^(\d+) projects?$/, '$1 个项目');
        }
        if (!translated) {
            for (const [pattern, replacement] of zhCnSettingsPatterns) {
                if (pattern.test(trimmed)) {
                    translated = trimmed.replace(pattern, replacement);
                    break;
                }
            }
        }
    }
    if (!translated) {
        for (const [pattern, replacement] of zhCnPatterns) {
            if (pattern.test(trimmed)) {
                translated = trimmed.replace(pattern, replacement);
                break;
            }
        }
    }
    if (!translated || translated === trimmed) {
        return value;
    }
    const prefix = value.match(/^\s*/)?.[0] ?? '';
    const suffix = value.match(/\s*$/)?.[0] ?? '';
    return `${prefix}${translated}${suffix}`;
}
function translateElementAttributes(element) {
    const allowSettingsFragments = !!element.closest?.('[role="dialog"]');
    for (const attr of ['title', 'aria-label', 'placeholder']) {
        const value = element.getAttribute?.(attr);
        if (value) {
            const translated = translateString(value, allowSettingsFragments);
            if (translated !== value) {
                element.setAttribute(attr, translated);
            }
        }
    }
}
function translateNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
        if (node.parentElement?.closest?.('script, style, textarea, code, pre, [contenteditable="true"]')) {
            return;
        }
        const allowSettingsFragments = !!node.parentElement?.closest?.('[role="dialog"]');
        const translated = translateString(node.nodeValue || '', allowSettingsFragments);
        if (translated !== node.nodeValue) {
            node.nodeValue = translated;
        }
        return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) {
        return;
    }
    const element = node;
    if (element.tagName === 'TEXTAREA') {
        translateElementAttributes(element);
        return;
    }
    if (['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(element.tagName)) {
        return;
    }
    if (element.getAttribute?.('contenteditable') === 'true') {
        return;
    }
    translateElementAttributes(element);
    // React renders this fixed empty-state sentence as three text siblings.
    const children = Array.from(element.childNodes);
    if (children.length > 1 && children.every(child => child.nodeType === Node.TEXT_NODE)
        && !element.closest?.('script, style, textarea, code, pre, [contenteditable="true"]')
        && children.map(child => child.nodeValue || '').join('').trim() === 'No automations yet') {
        children[0].nodeValue = translateString(children.map(child => child.nodeValue || '').join(''));
        for (const child of children.slice(1)) child.nodeValue = '';
        return;
    }
    for (const child of element.childNodes) {
        translateNode(child);
    }
}
function installZhCnRuntimeTranslation() {
    const run = () => {
        if (!document.body) {
            return;
        }
        document.documentElement.lang = 'zh-CN';
        translateNode(document.body);
        const observer = new MutationObserver((mutations) => {
            for (const mutation of mutations) {
                if (mutation.type === 'characterData') {
                    translateNode(mutation.target);
                }
                else {
                    for (const node of mutation.addedNodes) {
                        translateNode(node);
                    }
                    if (mutation.target?.nodeType === Node.ELEMENT_NODE) {
                        translateElementAttributes(mutation.target);
                    }
                }
            }
        });
        observer.observe(document.body, {
            childList: true,
            subtree: true,
            characterData: true,
            attributes: true,
            attributeFilter: ['title', 'aria-label', 'placeholder'],
        });
        setTimeout(() => translateNode(document.body), 500);
        setTimeout(() => translateNode(document.body), 1500);
    };
    if (document.readyState === 'loading') {
        window.addEventListener('DOMContentLoaded', run, { once: true });
    }
    else {
        run();
    }
}
installZhCnRuntimeTranslation();
